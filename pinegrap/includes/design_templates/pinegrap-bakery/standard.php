// The block a record view shows when its record is missing: an icon, a
// title, the widget's own message and the way back.
$bk_not_found = function ($icon_name, $title, $message, $back_text, $back_key) use ($el, $icon, $heading, $para, $link, $bind, $show_when) {
    return $el('div', 'text-center py-5', lang('Not Found'), array(
        $icon($icon_name, 'display-5 text-body-tertiary'),
        $heading('h2', $title, 'h3 fw-semibold mt-3'),
        $para($message, 'text-body-secondary mb-4', $bind('not_found')),
        $link($back_text, '{{page:' . $back_key . '}}', 'btn btn-primary rounded-pill px-4'),
    ), $show_when('record_not_found'));
};

// The line over a record: back to its list, and the staff's edit button.
$bk_back_bar = function ($back_key, $back_text) use ($el, $icon, $span, $edit_button) {
    return $el('div', 'd-flex flex-wrap align-items-center justify-content-between gap-2 mb-4', lang('Toolbar'), array(
        $el('a', 'd-inline-flex align-items-center gap-1 small fw-semibold link-primary text-decoration-none', lang('Link'), array(
            $icon('bi-arrow-left'),
            $span($back_text, '', lang('Link Text')),
        ), array('href' => '{{page:' . $back_key . '}}')),
        $edit_button(),
    ));
};

