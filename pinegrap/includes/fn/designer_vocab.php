/**
 * Builds the vocabulary from the shipped Bootstrap files.
 *
 * @param string $css      Text of bootstrap.min.css.
 * @param array  $js_map   Decoded bootstrap.bundle.min.js.map (sources, sourcesContent).
 * @return array           version, breakpoints, classes, tokens, js, fixed.
 */
function pg_designer_vocab_build($css, $js_map)
{
	$version = '';

	if (preg_match('/Bootstrap\s+v(\d+\.\d+\.\d+)/', $css, $m)) {
		$version = $m[1];
	}

	$rules = pg_designer_vocab_css_rules($css);
	$breakpoints = pg_designer_vocab_breakpoints($rules);

	return array(
		'version' => $version,
		'breakpoints' => $breakpoints,
		'classes' => pg_designer_vocab_classes($rules, $breakpoints),
		'tokens' => pg_designer_vocab_tokens($rules),
		'js' => pg_designer_vocab_js($js_map),
		'fixed' => pg_designer_vocab_fixed(),
	);
}

/**
 * The vocabulary as the JSON text stored in assets/js/designer_vocab/: one
 * line, keys in the order built, so a rebuild gives the same bytes.
 */
function pg_designer_vocab_json($vocab)
{
	return json_encode($vocab, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . "\n";
}

/**
 * Colour classes that keep one fixed colour whatever the colour mode
 * (data-bs-theme), or that Bootstrap 5.3 deprecated, each with the class that
 * follows the mode. The predictor ranks them last and offers the replacement.
 * This list is chosen, not read from the CSS: the CSS cannot say which fixed
 * colour a design means to keep.
 */
function pg_designer_vocab_fixed()
{
	return array(
		'bg-white' => 'bg-body',
		'bg-light' => 'bg-body-tertiary',
		'text-dark' => 'text-body-emphasis',
		'text-black' => 'text-body-emphasis',
		'text-muted' => 'text-body-secondary',
		'text-black-50' => 'text-body-secondary',
	);
}

/**
 * Splits CSS text into style rules. Each rule is array(media, selectors,
 * declarations): media is the @media/@supports prelude chain joined by ' & '
 * ('' at the top level), selectors the selector list as written, declarations
 * a list of array(property, value). @keyframes, @font-face and other blocks
 * that hold no style rules are skipped.
 */
function pg_designer_vocab_css_rules($css)
{
	// Comments first; they may hold braces.
	$css = preg_replace('#/\*.*?\*/#s', '', $css);
	$rules = array();
	$pos = 0;
	pg_designer_vocab_css_block($css, $pos, strlen($css), '', $rules);

	return $rules;
}

// Reads the rules between $pos and the closing brace of the block it is in
// (or $end); $pos is left after that brace.
function pg_designer_vocab_css_block($css, &$pos, $end, $media, &$rules)
{
	while ($pos < $end) {
		$start = $pos;
		$stop = pg_designer_vocab_css_scan($css, $pos, $end, '{;}');

		if ($stop === null) {
			return;
		}

		$char = $css[$stop];
		$prelude = trim(substr($css, $start, $stop - $start));
		$pos = $stop + 1;

		if ($char === '}') {
			return;
		}

		if ($char === ';') {
			continue;
		}

		if ($prelude !== '' && $prelude[0] === '@') {
			if (preg_match('/^@(media|supports|layer|container)\b/i', $prelude)) {
				$inner = ($media === '') ? $prelude : $media . ' & ' . $prelude;
				pg_designer_vocab_css_block($css, $pos, $end, $inner, $rules);
			} else {
				pg_designer_vocab_css_skip($css, $pos, $end);
			}

			continue;
		}

		$body_start = $pos;
		pg_designer_vocab_css_skip($css, $pos, $end);
		$body = substr($css, $body_start, $pos - 1 - $body_start);
		$rules[] = array($media, $prelude, pg_designer_vocab_css_declarations($body));
	}
}

// Returns the offset of the first of $stops outside strings, brackets and
// parentheses, or null.
function pg_designer_vocab_css_scan($css, $pos, $end, $stops)
{
	$depth = 0;
	$quote = '';

	for ($i = $pos; $i < $end; $i++) {
		$c = $css[$i];

		if ($quote !== '') {
			if ($c === '\\') {
				$i++;
			} elseif ($c === $quote) {
				$quote = '';
			}
		} elseif ($c === '"' || $c === "'") {
			$quote = $c;
		} elseif ($c === '\\') {
			$i++;
		} elseif ($c === '(' || $c === '[') {
			$depth++;
		} elseif ($c === ')' || $c === ']') {
			$depth--;
		} elseif ($depth <= 0 && strpos($stops, $c) !== false) {
			return $i;
		}
	}

	return null;
}

// Moves $pos past the brace that closes the block it is in.
function pg_designer_vocab_css_skip($css, &$pos, $end)
{
	$level = 1;

	while ($pos < $end) {
		$stop = pg_designer_vocab_css_scan($css, $pos, $end, '{}');

		if ($stop === null) {
			$pos = $end;
			return;
		}

		$pos = $stop + 1;
		$level += ($css[$stop] === '{') ? 1 : -1;

		if ($level === 0) {
			return;
		}
	}
}

function pg_designer_vocab_css_declarations($body)
{
	$out = array();

	foreach (pg_designer_vocab_split($body, ';') as $part) {
		$colon = pg_designer_vocab_css_scan($part, 0, strlen($part), ':');

		if ($colon === null) {
			continue;
		}

		$property = trim(substr($part, 0, $colon));
		$value = trim(substr($part, $colon + 1));

		if ($property !== '') {
			$out[] = array($property, $value);
		}
	}

	return $out;
}

// Splits on a character outside strings, brackets and parentheses.
function pg_designer_vocab_split($text, $char)
{
	$parts = array();
	$pos = 0;
	$end = strlen($text);

	while ($pos <= $end) {
		$stop = pg_designer_vocab_css_scan($text, $pos, $end, $char);

		if ($stop === null) {
			$parts[] = substr($text, $pos);
			break;
		}

		$parts[] = substr($text, $pos, $stop - $pos);
		$pos = $stop + 1;
	}

	return $parts;
}

/**
 * Splits one selector into its compound selectors, combinators dropped:
 * '.navbar-expand-lg .navbar-nav>.nav-link:hover' gives three compounds, the
 * last one being the subject.
 */
function pg_designer_vocab_compounds($selector)
{
	$compounds = array();
	$current = '';
	$depth = 0;
	$length = strlen($selector);

	for ($i = 0; $i < $length; $i++) {
		$c = $selector[$i];

		if ($c === '(' || $c === '[') {
			$depth++;
		} elseif ($c === ')' || $c === ']') {
			$depth--;
		}

		if ($depth === 0 && ($c === ' ' || $c === '>' || $c === '+' || $c === '~')) {
			if (trim($current) !== '') {
				$compounds[] = trim($current);
			}

			$current = '';
			continue;
		}

		$current .= $c;
	}

	if (trim($current) !== '') {
		$compounds[] = trim($current);
	}

	return $compounds;
}

/**
 * The class names of one compound selector, leaving out those inside
 * :not(), :is(), :has() and attribute brackets.
 */
function pg_designer_vocab_compound_classes($compound)
{
	$plain = '';
	$depth = 0;
	$length = strlen($compound);

	for ($i = 0; $i < $length; $i++) {
		$c = $compound[$i];

		if ($c === '(' || $c === '[') {
			$depth++;
		} elseif ($c === ')' || $c === ']') {
			$depth--;
			continue;
		}

		if ($depth === 0) {
			$plain .= $c;
		}
	}

	preg_match_all('/\.(-?[_a-zA-Z][_a-zA-Z0-9-]*)/', $plain, $m);

	return array_values(array_unique($m[1]));
}

/**
 * The grid breakpoints, from the min-width the .col-<bp> rules sit under:
 * array('sm' => '576px', ...), smallest first.
 */
function pg_designer_vocab_breakpoints($rules)
{
	$found = array();

	foreach ($rules as $rule) {
		if ($rule[0] === '' || !preg_match('/min-width:\s*([0-9.]+px)/', $rule[0], $width)) {
			continue;
		}

		foreach (pg_designer_vocab_split($rule[1], ',') as $selector) {
			if (preg_match('/^\.col-([a-z]+)$/', trim($selector), $m)) {
				$found[$m[1]] = $width[1];
			}
		}
	}

	uasort($found, function ($a, $b) {
		return (float) $a <=> (float) $b;
	});

	return $found;
}

/**
 * Every class the CSS names, sorted by name. Each entry holds only the keys
 * that apply:
 *   p    declarations of the rules whose whole selector is the class alone,
 *        as array(property => value); top-level rules win over @media ones
 *   r    array(breakpoint, name without it) for a responsive variant
 *        ('d-md-flex' => array('md', 'd-flex'))
 *   ctx  classes an ancestor or earlier sibling must carry for a rule to
 *        style it ('nav-link' => 'nav', 'navbar-nav'...)
 *   with classes set on the same element in a rule that styles it ('active',
 *        'show', 'is-valid'...)
 */
function pg_designer_vocab_classes($rules, $breakpoints)
{
	$classes = array();
	$exact = array();

	foreach ($rules as $rule) {
		list($media, $selector_list, $declarations) = $rule;

		foreach (pg_designer_vocab_split($selector_list, ',') as $selector) {
			$selector = trim($selector);
			$compounds = pg_designer_vocab_compounds($selector);

			if (!$compounds) {
				continue;
			}

			$subject = pg_designer_vocab_compound_classes(array_pop($compounds));
			$context = array();

			foreach ($compounds as $compound) {
				foreach (pg_designer_vocab_compound_classes($compound) as $name) {
					$context[$name] = true;
					pg_designer_vocab_class_entry($classes, $name);
				}
			}

			foreach ($subject as $name) {
				pg_designer_vocab_class_entry($classes, $name);

				foreach ($context as $other => $unused) {
					if ($other !== $name) {
						$classes[$name]['ctx'][$other] = true;
					}
				}

				foreach ($subject as $other) {
					if ($other !== $name) {
						$classes[$name]['with'][$other] = true;
					}
				}
			}

			if (preg_match('/^\.(-?[_a-zA-Z][_a-zA-Z0-9-]*)$/', $selector, $m)) {
				$exact[$m[1]][$media][] = $declarations;
			}
		}
	}

	ksort($classes, SORT_STRING);
	$out = array();

	foreach ($classes as $name => $entry) {
		$item = array();

		if (isset($exact[$name])) {
			// Top-level rules when there are any, else the first @media.
			$by_media = $exact[$name];
			$chosen = isset($by_media['']) ? $by_media[''] : reset($by_media);
			$declarations = array();

			foreach ($chosen as $list) {
				foreach ($list as $declaration) {
					$declarations[$declaration[0]] = $declaration[1];
				}
			}

			if ($declarations) {
				$item['p'] = $declarations;
			}
		}

		$responsive = pg_designer_vocab_responsive($name, $classes, $breakpoints);

		if ($responsive !== null) {
			$item['r'] = $responsive;
		}

		foreach (array('ctx', 'with') as $key) {
			if (!empty($entry[$key])) {
				$list = array_keys($entry[$key]);
				sort($list, SORT_STRING);
				$item[$key] = $list;
			}
		}

		// An empty object, not an empty list, in the JSON.
		$out[$name] = $item ? $item : new stdClass();
	}

	return $out;
}

function pg_designer_vocab_class_entry(&$classes, $name)
{
	if (!isset($classes[$name])) {
		$classes[$name] = array('ctx' => array(), 'with' => array());
	}
}

/**
 * array(breakpoint, name without it) when a segment of the class name is a
 * breakpoint and the same name exists for every breakpoint ('col-md-6',
 * 'd-lg-none', 'modal-fullscreen-sm-down'); null otherwise. The "every
 * breakpoint" test keeps size modifiers out ('btn-sm', 'modal-lg': there is
 * no 'btn-md' or 'modal-md').
 */
function pg_designer_vocab_responsive($name, $classes, $breakpoints)
{
	$segments = explode('-', $name);

	foreach ($segments as $index => $segment) {
		if (!isset($breakpoints[$segment])) {
			continue;
		}

		$all = true;

		foreach ($breakpoints as $bp => $unused) {
			$variant = $segments;
			$variant[$index] = $bp;

			if (!isset($classes[implode('-', $variant)])) {
				$all = false;
				break;
			}
		}

		if ($all) {
			$base = $segments;
			array_splice($base, $index, 1);

			return array($segment, implode('-', $base));
		}
	}

	return null;
}

/**
 * The CSS custom properties Bootstrap defines, sorted by name. Each entry:
 *   v   value in the light colour mode (':root' or the first class rule)
 *   d   value in the dark mode, when [data-bs-theme=dark] sets one
 *   on  classes whose own rule (selector the class alone) sets it, for a
 *       component's tokens ('--bs-btn-bg' => 'btn', 'btn-primary'...)
 */
function pg_designer_vocab_tokens($rules)
{
	$tokens = array();

	foreach ($rules as $rule) {
		list($media, $selector_list, $declarations) = $rule;
		$selectors = array_map('trim', pg_designer_vocab_split($selector_list, ','));
		$root = in_array(':root', $selectors, true);
		$dark = in_array('[data-bs-theme=dark]', $selectors, true);

		foreach ($declarations as $declaration) {
			list($property, $value) = $declaration;

			if (strpos($property, '--') !== 0) {
				continue;
			}

			if (!isset($tokens[$property])) {
				$tokens[$property] = array();
			}

			if ($media !== '') {
				continue;
			}

			if ($dark) {
				if (!isset($tokens[$property]['d'])) {
					$tokens[$property]['d'] = $value;
				}

				continue;
			}

			if ($root) {
				$tokens[$property]['v'] = $value;
				continue;
			}

			foreach ($selectors as $selector) {
				if (preg_match('/^\.(-?[_a-zA-Z][_a-zA-Z0-9-]*)$/', $selector, $m)) {
					if (!isset($tokens[$property]['v'])) {
						$tokens[$property]['v'] = $value;
					}

					$tokens[$property]['on'][$m[1]] = true;
				}
			}
		}
	}

	ksort($tokens, SORT_STRING);
	$out = array();

	foreach ($tokens as $name => $entry) {
		$item = array();

		foreach (array('v', 'd') as $key) {
			if (isset($entry[$key])) {
				$item[$key] = $entry[$key];
			}
		}

		if (!empty($entry['on'])) {
			$on = array_keys($entry['on']);
			sort($on, SORT_STRING);
			$item['on'] = $on;
		}

		$out[$name] = $item ? $item : new stdClass();
	}

	return $out;
}

/**
 * The JavaScript components, keyed by their data name ('modal'), sorted. Read
 * from the original sources the bundle's source map carries. Each entry:
 *   class    the class on window.bootstrap ('Modal')
 *   methods  public instance methods, inherited ones included
 *   static   public static methods ('getInstance', 'getOrCreateInstance')
 *   events   events it triggers, short names: 'show' is 'show.bs.modal'
 *   options  array(name => array(type, default as written in the source))
 *   attrs    data attributes it reads, each with the values it knows
 *            ('data-bs-toggle' => array('modal')); every option is also a
 *            data-bs-<kebab-name> attribute with no fixed values
 */
function pg_designer_vocab_js($js_map)
{
	$sources = array();

	if (isset($js_map['sources'], $js_map['sourcesContent'])) {
		foreach ($js_map['sources'] as $index => $path) {
			if (preg_match('#js/src/([a-z-]+)\.js$#', $path, $m) && isset($js_map['sourcesContent'][$index])) {
				$sources[$m[1]] = $js_map['sourcesContent'][$index];
			}
		}
	}

	$parsed = array();

	foreach ($sources as $file => $source) {
		$parsed[$file] = pg_designer_vocab_js_parse($source);
	}

	$by_class = array();

	foreach ($parsed as $file => $info) {
		if ($info['class'] !== '') {
			$by_class[$info['class']] = $file;
		}
	}

	$out = array();

	foreach ($parsed as $file => $info) {
		if ($info['name'] === '' || $info['class'] === '') {
			continue;
		}

		// Walk up the class chain for inherited methods, options and events.
		$chain = array($info);
		$parent = $info['extends'];

		while ($parent !== '' && isset($by_class[$parent])) {
			$up = $parsed[$by_class[$parent]];
			$chain[] = $up;
			$parent = $up['extends'];
		}

		$methods = array();
		$static = array();
		$events = array();
		$options = array();
		$types = array();
		$attrs = array();

		foreach (array_reverse($chain) as $level) {
			$methods = array_merge($methods, $level['methods']);
			$static = array_merge($static, $level['static']);
			$events = array_merge($events, $level['events']);

			// The source spreads the parent's Default first and overrides.
			$options = array_merge($options, $level['defaults']);
			$types = array_merge($types, $level['types']);
			$attrs = array_replace_recursive($attrs, $level['attrs']);
		}

		$methods = array_values(array_unique($methods));
		$static = array_values(array_unique($static));
		$events = array_values(array_unique($events));
		sort($methods, SORT_STRING);
		sort($static, SORT_STRING);
		sort($events, SORT_STRING);
		ksort($types, SORT_STRING);

		$option_list = array();

		foreach ($types as $option => $type) {
			$option_list[$option] = array($type, isset($options[$option]) ? $options[$option] : '');
		}

		if ($info['dismiss']) {
			$attrs['data-bs-dismiss'][$info['name']] = true;
		}

		$list = array();
		ksort($attrs, SORT_STRING);

		foreach ($attrs as $attr => $values) {
			$values = array_keys($values);
			sort($values, SORT_STRING);
			$list[$attr] = $values;
		}

		$entry = array('class' => $info['class'], 'methods' => $methods, 'static' => $static, 'events' => $events);
		$entry['options'] = $option_list ? $option_list : new stdClass();
		$entry['attrs'] = $list ? $list : new stdClass();
		$out[$info['name']] = $entry;
	}

	ksort($out, SORT_STRING);

	return $out;
}

/**
 * What one component source declares: name, class, extends, methods, static,
 * events, defaults, types, attrs (array(attr => array(value => true))),
 * dismiss (whether it registers a data-bs-dismiss trigger).
 */
function pg_designer_vocab_js_parse($source)
{
	$info = array(
		'name' => '',
		'class' => '',
		'extends' => '',
		'methods' => array(),
		'static' => array(),
		'events' => array(),
		'defaults' => array(),
		'types' => array(),
		'attrs' => array(),
		'dismiss' => false,
	);

	if (preg_match("/^const NAME = '([a-z]+)'/m", $source, $m)) {
		$info['name'] = $m[1];
	}

	if (preg_match('/^class (\w+)(?: extends (\w+))? \{/m', $source, $m)) {
		$info['class'] = $m[1];
		$info['extends'] = isset($m[2]) ? $m[2] : '';
	}

	// Class members sit at two spaces; getters and names starting with "_"
	// are not the public API, nor the jQuery bridge and the event-name helper.
	preg_match_all('/^  (static )?([a-zA-Z]\w*)\([^)]*\) \{(?: \/\/.*)?$/m', $source, $members, PREG_SET_ORDER);

	foreach ($members as $member) {
		$name = $member[2];

		if ($name === 'constructor' || $name === 'jQueryInterface' || $name === 'eventName') {
			continue;
		}

		$info[$member[1] !== '' ? 'static' : 'methods'][] = $name;
	}

	// Event constants: `show${EVENT_KEY}` or a plain 'show'. Public are the
	// ones the component triggers; the rest are listeners it binds.
	$constants = array();
	preg_match_all('/^const (EVENT_\w+) = (?:`(\w+)\$\{EVENT_KEY\}`|\'(\w+)\')$/m', $source, $found, PREG_SET_ORDER);

	foreach ($found as $event) {
		$constants[$event[1]] = ($event[2] !== '') ? $event[2] : $event[3];
	}

	preg_match_all('/(?:EventHandler\.trigger\([^,]+,\s*(?:this\.constructor\.eventName\()?|triggerEvent\()(EVENT_\w+)/', $source, $triggered);

	foreach ($triggered[1] as $constant) {
		if (isset($constants[$constant])) {
			$info['events'][] = $constants[$constant];
		}
	}

	$info['defaults'] = pg_designer_vocab_js_object($source, 'Default');
	$info['types'] = pg_designer_vocab_js_object($source, 'DefaultType');

	foreach ($info['types'] as $type => $value) {
		$info['types'][$type] = trim($value, "'");
	}

	// Data attributes named in the source, with a value where it is fixed;
	// those it writes itself (data-bs-original-title) are not the author's.
	preg_match_all('/data-bs-([a-z][a-z-]*)(?:="([a-z]+)")?/', $source, $found, PREG_SET_ORDER);
	preg_match_all("/setAttribute\\('(data-bs-[a-z-]+)'/", $source, $written);

	foreach ($found as $attr) {
		if (!in_array('data-bs-' . $attr[1], $written[1], true)) {
			pg_designer_vocab_js_attr($info['attrs'], 'data-bs-' . $attr[1], isset($attr[2]) ? $attr[2] : '');
		}
	}

	preg_match_all("/getAttribute\('(data-bs-[a-z-]+)'\) === '([a-z]+)'/", $source, $found, PREG_SET_ORDER);

	foreach ($found as $attr) {
		pg_designer_vocab_js_attr($info['attrs'], $attr[1], $attr[2]);
	}

	if (preg_match('/getElementFromSelector|getMultipleElementsFromSelector|getSelectorFromElement/', $source)) {
		pg_designer_vocab_js_attr($info['attrs'], 'data-bs-target', '');
	}

	foreach ($info['types'] as $option => $unused) {
		$kebab = strtolower(preg_replace('/([A-Z])/', '-$1', $option));
		pg_designer_vocab_js_attr($info['attrs'], 'data-bs-' . $kebab, '');
	}

	$info['dismiss'] = (bool) preg_match('/^enableDismissTrigger\(/m', $source);

	return $info;
}

function pg_designer_vocab_js_attr(&$attrs, $attr, $value)
{
	if (!isset($attrs[$attr])) {
		$attrs[$attr] = array();
	}

	if ($value !== '') {
		$attrs[$attr][$value] = true;
	}
}

/**
 * The top-level members of `const <name> = { ... }` as array(key => value
 * text, whitespace collapsed); a `...Parent.<name>` spread is left out (the
 * caller merges the parent's own).
 */
function pg_designer_vocab_js_object($source, $name)
{
	if (!preg_match('/^const ' . preg_quote($name, '/') . ' = \{/m', $source, $m, PREG_OFFSET_CAPTURE)) {
		return array();
	}

	$start = $m[0][1] + strlen($m[0][0]);
	$end = strlen($source);
	$pos = $start;
	pg_designer_vocab_css_skip($source, $pos, $end);
	$body = substr($source, $start, $pos - 1 - $start);
	$out = array();

	foreach (pg_designer_vocab_js_members($body) as $member) {
		$member = trim(preg_replace('/\s+/', ' ', $member));

		if ($member === '' || strpos($member, '...') === 0) {
			continue;
		}

		if (preg_match('/^(\w+):\s*(.*)$/s', $member, $pair)) {
			$out[$pair[1]] = $pair[2];
		}
	}

	return $out;
}

// Splits an object body on commas outside strings, brackets, parentheses and
// braces.
function pg_designer_vocab_js_members($body)
{
	$parts = array();
	$current = '';
	$depth = 0;
	$quote = '';
	$length = strlen($body);

	for ($i = 0; $i < $length; $i++) {
		$c = $body[$i];

		if ($quote !== '') {
			$current .= $c;

			if ($c === '\\' && $i + 1 < $length) {
				$current .= $body[++$i];
			} elseif ($c === $quote) {
				$quote = '';
			}

			continue;
		}

		if ($c === '"' || $c === "'" || $c === '`') {
			$quote = $c;
		} elseif (strpos('([{', $c) !== false) {
			$depth++;
		} elseif (strpos(')]}', $c) !== false) {
			$depth--;
		} elseif ($c === ',' && $depth === 0) {
			$parts[] = $current;
			$current = '';
			continue;
		}

		$current .= $c;
	}

	$parts[] = $current;

	return $parts;
}
